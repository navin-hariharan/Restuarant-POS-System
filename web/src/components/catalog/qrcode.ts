/**
 * Minimal QR Code encoder (byte mode, versions 1-40, automatic mask selection).
 * Port of the reference algorithm by Project Nayuki (MIT). No dependencies.
 *
 * `encodeQr('https://...', 'M')` returns a square boolean matrix (true = dark module).
 */
export type QrEcc = 'L' | 'M' | 'Q' | 'H';

const ECC_FORMAT: Record<QrEcc, number> = { L: 1, M: 0, Q: 3, H: 2 };
const ECC_INDEX: Record<QrEcc, number> = { L: 0, M: 1, Q: 2, H: 3 };

